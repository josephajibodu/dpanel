<?php

namespace App\Services\Nginx\ConfigGenerators;

use App\Enums\WwwRedirect;
use App\Models\Site;
use App\Models\SiteDomain;

abstract class BaseNginxConfigGenerator
{
    /**
     * Generate the server block content for this project type.
     */
    abstract protected function generateServerBlock(Site $site): string;

    /**
     * Generate the complete Nginx configuration for a single site domain (one
     * file per domain): the redirects flitops manages, the site itself, and
     * the places the user's own files are included.
     */
    public function generateForSiteDomain(Site $site, SiteDomain $domain, bool $ssl = false): string
    {
        $appName = config('app.name');
        $snippetsBase = $domain->nginxSnippetsBasePath();
        $title = $ssl ? "{$domain->hostname} (SSL)" : $domain->hostname;

        $header = <<<NGINX
# Nginx configuration for {$title}
# Generated by {$appName}
# FLITOPS MANAGED - DO NOT EDIT. This file is rewritten whenever the site
# changes. Add your own configuration from the site's Web Server tab.
NGINX;

        return implode("\n\n", array_filter([
            $header,
            $ssl ? $this->httpsRedirectBlock($site, $domain) : '',
            $this->wwwRedirectBlock($site, $domain, $ssl),
            $this->siteBlock($site, $domain, $ssl),
            "include {$snippetsBase}/after/*.conf;",
        ]));
    }

    /**
     * Build server_name for a single domain row (one config file).
     */
    protected function buildServerNamesForDomain(SiteDomain $domain): string
    {
        if ($domain->effectiveWwwRedirect() === WwwRedirect::ToWww) {
            return $domain->wwwHostname();
        }

        $names = [$domain->hostname];

        if ($domain->wildcard_enabled && ! str_starts_with(strtolower($domain->hostname), 'www.')) {
            $names[] = '*.'.$domain->hostname;
        }

        return implode(' ', $names);
    }

    /**
     * The site's own server block.
     */
    protected function siteBlock(Site $site, SiteDomain $domain, bool $ssl): string
    {
        $snippetsBase = $domain->nginxSnippetsBasePath();
        $errorLog = $site->server->webServer()->errorLogPath($site->ulid);

        $listen = $ssl
            ? <<<'NGINX'
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
NGINX
            : <<<'NGINX'
    listen 80;
    listen [::]:80;
NGINX;

        $tls = $ssl
            ? <<<NGINX

{$this->certificateDirectives($site, $domain)}
    ssl_prefer_server_ciphers off;
    ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305:DHE-RSA-AES128-GCM-SHA256:DHE-RSA-AES256-GCM-SHA384;

    add_header Strict-Transport-Security "max-age=63072000" always;

NGINX
            : '';

        return <<<NGINX
server {
{$listen}
    server_name {$this->buildServerNamesForDomain($domain)};
{$tls}
    error_log {$errorLog};

{$this->acmeChallengeLocation($site)}

{$this->generateServerBlock($site)}

    # Files added on the site's Web Server tab ("Inside the site block")
    include {$snippetsBase}/server/*.conf;
}
NGINX;
    }

    /**
     * Sends plain-HTTP visitors of an HTTPS site to HTTPS.
     */
    protected function httpsRedirectBlock(Site $site, SiteDomain $domain): string
    {
        return <<<NGINX
# Send HTTP visitors to HTTPS
server {
    listen 80;
    listen [::]:80;
    server_name {$this->buildServerNamesForDomain($domain)};
    server_tokens off;

{$this->acmeChallengeLocation($site)}

    location / {
        return 301 https://\$host\$request_uri;
    }
}
NGINX;
    }

    /**
     * Redirects between a bare domain and its www twin, when the domain is
     * set to. With HTTPS the same block answers on both ports, so visitors
     * reach the right address in one hop.
     */
    protected function wwwRedirectBlock(Site $site, SiteDomain $domain, bool $ssl): string
    {
        $redirect = $domain->effectiveWwwRedirect();

        if ($redirect === WwwRedirect::None) {
            return '';
        }

        [$from, $to] = $redirect === WwwRedirect::FromWww
            ? [$domain->wwwHostname(), $domain->hostname]
            : [$domain->hostname, $domain->wwwHostname()];

        $scheme = $ssl ? 'https' : 'http';

        $tls = $ssl
            ? <<<NGINX
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
{$this->certificateDirectives($site, $domain)}

NGINX
            : '';

        return <<<NGINX
# Redirect {$from} to {$to}
server {
    listen 80;
    listen [::]:80;
{$tls}    server_name {$from};
    server_tokens off;

{$this->acmeChallengeLocation($site)}

    location / {
        return 301 {$scheme}://{$to}\$request_uri;
    }
}
NGINX;
    }

    /**
     * The certificate flitops installed for this domain: the free-domain
     * wildcard, or the one certbot obtained for a custom domain.
     */
    protected function certificateDirectives(Site $site, SiteDomain $domain): string
    {
        $directory = $site->server->webServer()->certificateDirectory($site->id, $domain->id);

        return <<<NGINX
    ssl_certificate {$directory}/server.crt;
    ssl_certificate_key {$directory}/server.key;
    ssl_protocols TLSv1.2 TLSv1.3;
NGINX;
    }

    /**
     * Serves Let's Encrypt's ownership checks from the folder certbot writes
     * them into (see Site::acmeChallengeRoot()), ahead of every other rule,
     * so certificates keep renewing whatever the site itself does.
     */
    protected function acmeChallengeLocation(Site $site): string
    {
        return <<<NGINX
    location ^~ /.well-known/acme-challenge/ {
        root {$site->acmeChallengeRoot()};
        default_type text/plain;
    }
NGINX;
    }

    /**
     * Get common security headers.
     */
    protected function getSecurityHeaders(): string
    {
        return <<<'NGINX'
    add_header X-Frame-Options "SAMEORIGIN";
    add_header X-Content-Type-Options "nosniff";
NGINX;
    }

    /**
     * Get common PHP-FPM configuration.
     *
     * The FastCGI buffers are raised above Nginx's 4–8 KB default so large
     * response headers (e.g. Laravel's preload Link header) don't fail with
     * "upstream sent too big header" and a 502.
     */
    protected function getPhpFpmConfig(Site $site, string $phpVersion): string
    {
        return <<<NGINX
    # PHP-FPM configuration
    location ~ \.php$ {
        fastcgi_pass unix:{$site->phpFpmSocket($phpVersion)};
        fastcgi_param SCRIPT_FILENAME \$realpath_root\$fastcgi_script_name;
        include fastcgi_params;
        fastcgi_hide_header X-Powered-By;
        fastcgi_buffers 16 16k;
        fastcgi_buffer_size 32k;
    }
NGINX;
    }

    /**
     * Get common hidden files protection.
     */
    protected function getHiddenFilesProtection(): string
    {
        return <<<'NGINX'
    # Deny access to hidden files
    location ~ /\.(?!well-known).* {
        deny all;
    }
NGINX;
    }

    /**
     * Get common favicon and robots.txt handling.
     */
    protected function getCommonLocations(): string
    {
        return <<<'NGINX'
    location = /favicon.ico { access_log off; log_not_found off; }
    location = /robots.txt  { access_log off; log_not_found off; }
NGINX;
    }
}
