<?php

namespace App\Services\Caddy;

use App\Enums\ProjectType;
use App\Enums\WwwRedirect;
use App\Models\Site;
use App\Models\SiteDomain;

/**
 * Builds the Caddy config for one domain of a site: the site block, plus a
 * redirect block when the domain redirects between www and the bare domain.
 */
class CaddyConfigGenerator
{
    /**
     * @param  bool  $ssl  Serve over HTTPS. Without it the addresses are http:// so Caddy doesn't fetch a certificate.
     * @param  string|null  $certificateDirectory  Use the certificate installed here instead of letting Caddy obtain one.
     */
    public function generate(Site $site, SiteDomain $domain, bool $ssl, ?string $certificateDirectory = null): string
    {
        $hostname = $domain->hostname;
        $appName = config('app.name');
        $scheme = $ssl ? '' : 'http://';
        $tls = $certificateDirectory !== null
            ? "\ttls {$certificateDirectory}/server.crt {$certificateDirectory}/server.key\n"
            : '';
        $snippetsBase = $domain->nginxSnippetsBasePath();

        $hsts = $ssl ? "\n\t\tStrict-Transport-Security \"max-age=63072000\"" : '';

        $siteBlock = <<<CADDY
# Caddy configuration for {$hostname}
# Generated by {$appName}
# FLITOPS MANAGED - DO NOT EDIT. This file is rewritten whenever the site
# changes. Add your own configuration from the site's Web Server tab.

{$this->addresses($domain, $scheme, $certificateDirectory !== null || ! $ssl)} {
{$tls}	root * {$site->webRoot()}
	encode zstd gzip

	header {
		X-Frame-Options "SAMEORIGIN"
		X-Content-Type-Options "nosniff"
		-Server
		-X-Powered-By{$hsts}
	}

	# Deny access to hidden files
	@hidden {
		path_regexp /\.
		not path /.well-known/*
	}
	respond @hidden 403

{$this->handlers($site)}

	# Files added on the site's Web Server tab ("Inside the site block")
	import {$snippetsBase}/server/*.conf
}
CADDY;

        $redirectBlock = $this->wwwRedirectBlock($domain, $ssl, $tls);

        return $siteBlock."\n"
            .($redirectBlock !== '' ? "\n{$redirectBlock}\n" : '')
            ."\nimport {$snippetsBase}/after/*.conf\n";
    }

    /**
     * The site block's addresses. A wildcard is only added when Caddy won't
     * have to obtain the certificate itself, since it can't get a wildcard
     * certificate through the HTTP challenge.
     */
    private function addresses(SiteDomain $domain, string $scheme, bool $canServeWildcard): string
    {
        $hostname = $domain->hostname;

        if ($domain->effectiveWwwRedirect() === WwwRedirect::ToWww) {
            return $scheme.$domain->wwwHostname();
        }

        $addresses = [$scheme.$hostname];

        if ($domain->wildcard_enabled && ! str_starts_with(strtolower($hostname), 'www.') && $canServeWildcard) {
            $addresses[] = $scheme.'*.'.$hostname;
        }

        return implode(', ', $addresses);
    }

    private function handlers(Site $site): string
    {
        if ($site->usesOctane()) {
            return $this->octaneHandlers($site);
        }

        $projectType = $site->project_type ?? ProjectType::Laravel;

        if ($site->servesAsSinglePageApp()) {
            return $this->singlePageAppHandlers();
        }

        if ($projectType === ProjectType::StaticHtml) {
            return "\tfile_server";
        }

        $socket = $site->phpFpmSocket($site->php_version ?: '8.3');

        // resolve_root_symlink makes PHP see the real release folder behind
        // `current`, so a deploy's new code is picked up (like $realpath_root in Nginx).
        $php = <<<CADDY
	php_fastcgi unix/{$socket} {
		resolve_root_symlink
	}
	file_server
CADDY;

        if ($projectType === ProjectType::WordPress) {
            return "\trespond /wp-config.php 403\n\n{$php}";
        }

        return $php;
    }

    /**
     * A Laravel site on Octane: files that exist are served directly, and
     * every other request goes to the site's Octane process. Caddy runs
     * `route` before the site block's own hidden files rule, so the rule is
     * repeated inside it. The path rule's trailing-slash pattern stops a
     * request for a folder, such as `/`, being treated as a file.
     */
    private function octaneHandlers(Site $site): string
    {
        return <<<CADDY
	# Laravel Octane: files that exist are served directly, everything else goes to the Octane process
	route {
		respond @hidden 403
		@octaneStatic {
			file
			not path *.php */
		}
		file_server @octaneStatic
		reverse_proxy 127.0.0.1:{$site->octane_port}
	}
CADDY;
    }

    /**
     * URLs that match no file or folder get the app's index.html, except
     * missing assets (see Site::SINGLE_PAGE_APP_ASSET_EXTENSIONS), which
     * stay a 404. Caddy rewrites before it applies the hidden files rule,
     * and the rewrite only touches paths with no file behind them.
     */
    private function singlePageAppHandlers(): string
    {
        $assetPaths = implode(' ', array_map(
            fn (string $extension): string => "*.{$extension}",
            Site::SINGLE_PAGE_APP_ASSET_EXTENSIONS,
        ));

        return <<<CADDY
	# Single-page app: URLs that match no file get index.html, and the app shows the page
	@singlePageApp {
		not file {path} {path}/
		not path {$assetPaths}
	}
	rewrite @singlePageApp /index.html
	file_server
CADDY;
    }

    private function wwwRedirectBlock(SiteDomain $domain, bool $ssl, string $tls): string
    {
        $redirect = $domain->effectiveWwwRedirect();

        if ($redirect === WwwRedirect::None) {
            return '';
        }

        $scheme = $ssl ? '' : 'http://';
        $target = $ssl ? 'https://' : 'http://';

        [$from, $to] = $redirect === WwwRedirect::FromWww
            ? [$domain->wwwHostname(), $domain->hostname]
            : [$domain->hostname, $domain->wwwHostname()];

        return <<<CADDY
{$scheme}{$from} {
{$tls}	redir {$target}{$to}{uri} permanent
}
CADDY;
    }
}
